def style_axis(ax: plt.Axes) -> None:
    ax.grid(axis="y", color=GRID, linewidth=0.55, alpha=0.8)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.tick_params(labelsize=7)


def save_figure(fig: plt.Figure, name: str) -> None:
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    for ext in ("pdf", "svg"):
        fig.savefig(FIG_DIR / f"{name}.{ext}", bbox_inches="tight", pad_inches=0.025)
    plt.close(fig)


def render_dior_ablation(data: dict) -> None:
    d = data["dior"]
    labels = ["Baseline", "+TPC", "+HRR", "+SCA", "+PLP"]
    values = [d["baseline"], d["tpc_best"], d["hrr_best"], d["sca_best"], d["plp_best"]]
    values_pct = [100 * v for v in values]
    colors = [GRAY, BLUE, GREEN, PURPLE, ORANGE]
    fig, ax = plt.subplots(figsize=(3.45, 2.5))
    bars = ax.bar(range(5), values_pct, width=0.6, color=colors, edgecolor=INK, linewidth=0.4)
    bars[4].set_hatch("//")
    bars[4].set_alpha(0.75)
    scatter_groups = [None, d["rep_bests"]["tpc"], d["rep_bests"]["hrr"], d["rep_bests"]["sca"], d["rep_bests"]["plp"]]
    label_tops = list(values_pct)
    for xi, reps in enumerate(scatter_groups):
        if not reps:
            continue
        n = len(reps)
        for j, v in enumerate(sorted(reps)):
            offset = (j - (n - 1) / 2) * (0.32 / max(n - 1, 1))
            ax.scatter(xi + offset, 100 * v, s=13, facecolor="white", edgecolor=INK, linewidth=0.6, zorder=4)
        label_tops[xi] = max(label_tops[xi], 100 * max(reps))
    for xi, (v, top) in enumerate(zip(values_pct, label_tops)):
        ax.text(xi, top + 0.14, f"{v:.2f}", ha="center", va="bottom", fontsize=6.6)
    ax.annotate(
        "best run 69.92",
        xy=(3 + 0.16, 100 * d["sca_single"]),
        xytext=(1.15, 70.45),
        arrowprops={"arrowstyle": "->", "lw": 0.6, "color": PURPLE},
        fontsize=6.0,
    )
    ax.text(4, 70.55, "no further gain", ha="center", fontsize=6.0, color=MUTED)
    ax.set_xticks(range(5), labels)
    ax.set_ylabel(r"AP$_{50}$ (%)", fontsize=8)
    ax.set_ylim(64.5, 71.2)
    style_axis(ax)
    fig.tight_layout(pad=0.2)
    save_figure(fig, "geonexus_tgrs_dior_ablation")


def render_dota2_stability(data: dict) -> None:
    runs = data["dota2"]["runs"]
    x = list(range(len(runs)))
    bests = [100 * r.best_map for r in runs]
    finals = [100 * r.final_map for r in runs]
    fig, ax = plt.subplots(figsize=(3.45, 2.4))
    ax.axhline(100 * data["dota2"]["tpc"], color=BLUE, linestyle="--", linewidth=0.9, label="+TPC 61.77")
    for xi, b, f in zip(x, bests, finals):
        ax.plot([xi, xi], [f, b], color="#9b9b9b", linewidth=0.7, zorder=1)
    ax.scatter(x, bests, color=GREEN, marker="D", s=22, label="Best ckpt", zorder=3)
    ax.scatter(x, finals, color=ORANGE, marker="o", s=22, label="Final ckpt", zorder=3)
    ax.set_xticks(x, [r.name for r in runs], rotation=30, ha="right")
    ax.set_ylabel(r"AP$_{50}$ (%)", fontsize=8)
    ax.set_ylim(61.0, 62.5)
    ax.legend(frameon=False, loc="lower right", fontsize=5.8, ncol=2, handlelength=1.1, columnspacing=0.8)
    style_axis(ax)
    fig.tight_layout(pad=0.2)
    save_figure(fig, "geonexus_tgrs_dota2_hrr_stability")


