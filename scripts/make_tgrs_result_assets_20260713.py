@dataclass(frozen=True)
class Raw:
    """Cell whose contents are emitted verbatim (already valid LaTeX)."""

    value: str


def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def assert_round(name: str, actual: float, expected: float) -> None:
    if round(actual, 4) != expected:
        raise AssertionError(f"{name}: got {actual:.8f}, expected rounded {expected:.4f}")


def pct(x: float) -> str:
    return f"{100.0 * x:.2f}"


def tex_escape(text: str) -> str:
    repl = {
        "\\": r"\textbackslash{}",
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
        "{": r"\{",
        "}": r"\}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    return "".join(repl.get(ch, ch) for ch in text)


def render_cell(cell: object) -> str:
    if isinstance(cell, Bold):
        return rf"\textbf{{{render_cell(cell.value)}}}"
    if isinstance(cell, Raw):
        return cell.value
    if isinstance(cell, float):
        return pct(cell)
    return tex_escape(str(cell))


def csv_cell(cell: object) -> object:
    if isinstance(cell, Bold):
        return csv_cell(cell.value)
    if isinstance(cell, Raw):
        return cell.value
    if isinstance(cell, float):
        return pct(cell)
    return cell


def write_csv(path: Path, headers: list[object], rows: list[list[object]]) -> None:
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(headers)
        writer.writerows([[csv_cell(c) for c in row] for row in rows])


def latex_table(
    *,
    headers: list[object],
    rows: list[list[object]],
    caption: str,
    label: str,
    colspec: str,
    starred: bool = False,
    footnote: str | None = None,
    scale_to_width: str | None = None,
    size_cmd: str = r"\footnotesize",
) -> str:
    env = "table*" if starred else "table"
    body = [
        rf"\begin{{{env}}}[t]",
        r"\centering",
        size_cmd,
        rf"\caption{{{caption}}}",
        rf"\label{{{label}}}",
    ]
    if scale_to_width:
        body.append(rf"\resizebox{{{scale_to_width}}}{{!}}{{%")
    body.extend(
        [
            r"\begin{tabular}{" + colspec + r"}",
            r"\toprule",
            " & ".join(render_cell(h) for h in headers) + r" \\",
            r"\midrule",
        ]
    )
    for row in rows:
        if row == ["<midrule>"]:
            body.append(r"\midrule")
            continue
        body.append(" & ".join(render_cell(c) for c in row) + r" \\")
    body.extend([r"\bottomrule", r"\end{tabular}"])
    if scale_to_width:
        body.append(r"}")
    if footnote:
        body.append(r"\vspace{1mm}")
        body.append(r"\parbox{0.97\linewidth}{\scriptsize " + footnote + "}")
    body.append(rf"\end{{{env}}}")
    return "\n".join(body) + "\n"


